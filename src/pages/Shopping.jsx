import { useState, useEffect, useRef, useMemo } from 'react'
import { buildShoppingList, enrichIngredientsWithQuantities, categorizeIngredient } from '../utils/shopping'
import { getWeekRange, getWeekStart } from '../utils/format'

const CATEGORY_ORDER = [
  'Proteins & Meat', 'Seafood', 'Produce', 'Dairy & Eggs',
  'Pantry & Dry Goods', 'Herbs & Spices', 'Other'
]

function ShoppingShareModal({ categories, manualItems, mealObjects, quantities, onClose }) {
  const [copied, setCopied] = useState(false)

  const text = useMemo(() => {
    const range = getWeekRange()
    const lines = [`🛒 Shopping List — ${range}`, '']

    // Build merged category map
    const allCats = {}
    Object.entries(categories).forEach(([cat, items]) => { allCats[cat] = [...items] })
    manualItems.forEach(item => {
      if (!allCats[item.category]) allCats[item.category] = []
      if (!allCats[item.category].includes(item.name)) allCats[item.category].push(item.name)
    })
    Object.entries(allCats).forEach(([cat, items]) => {
      if (items.length) lines.push(`${cat}: ${items.join(', ')}`)
    })

    lines.push('')
    lines.push('━━━━━━━━━━━━━━━━━━━━')
    lines.push('')
    lines.push('📋 By Recipe:')

    mealObjects.forEach(meal => {
      lines.push('')
      lines.push(meal.name)
      const enriched = Array.isArray(quantities[meal.id]) ? quantities[meal.id] : (meal.ingredients || [])
      enriched.forEach(ing => lines.push(`  • ${ing}`))
    })

    lines.push('')
    lines.push('Generated by Mise en Place')
    return lines.join('\n')
  }, [categories, manualItems, mealObjects, quantities])

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(text)
      setCopied(true)
      setTimeout(() => setCopied(false), 2000)
    } catch { /* ignore */ }
  }

  return (
    <div className="modal-overlay" onClick={onClose}>
      <div className="modal modal-send slide-up" onClick={e => e.stopPropagation()}>
        <button className="modal-close" onClick={onClose}>✕</button>
        <h2 className="modal-title">📤 Send / Share</h2>
        <pre className="send-preview">{text}</pre>
        <div className="send-actions">
          <button className="btn btn-primary" onClick={handleCopy}>
            {copied ? '✓ Copied!' : 'Copy to Clipboard'}
          </button>
          <button className="btn btn-secondary" onClick={() => window.open('sms:?body=' + encodeURIComponent(text))}>
            Open in Messages
          </button>
          <button className="btn btn-secondary" onClick={() => window.open('mailto:?subject=Shopping List&body=' + encodeURIComponent(text))}>
            Open in Email
          </button>
        </div>
      </div>
    </div>
  )
}

export default function Shopping({ weekMeals, loading }) {
  const weekStart = getWeekStart()
  const storageKey = `shop-checked-${weekStart}`
  const manualKey = `shop-manual-${weekStart}`

  const [checked, setChecked] = useState(() => {
    try { return new Set(JSON.parse(localStorage.getItem(storageKey) || '[]')) }
    catch { return new Set() }
  })
  const [copied, setCopied] = useState(false)
  const [quantities, setQuantities] = useState({})
  const [showSend, setShowSend] = useState(false)
  const [manualInput, setManualInput] = useState('')
  const [manualItems, setManualItems] = useState(() => {
    try { return JSON.parse(localStorage.getItem(manualKey) || '[]') }
    catch { return [] }
  })
  const [pendingItems, setPendingItems] = useState([])
  const fetchedRef = useRef(new Set())

  const mealObjects = useMemo(() => weekMeals.map(wm => wm.meals).filter(Boolean), [weekMeals])
  const categories = useMemo(() => buildShoppingList(mealObjects), [mealObjects])

  const allCategoryKeys = useMemo(() => {
    const keys = new Set([
      ...Object.keys(categories),
      ...manualItems.map(m => m.category)
    ])
    return [
      ...CATEGORY_ORDER.filter(k => keys.has(k)),
      ...[...keys].filter(k => !CATEGORY_ORDER.includes(k))
    ]
  }, [categories, manualItems])

  const totalItems = Object.values(categories).reduce((sum, items) => sum + items.length, 0) + manualItems.length
  const totalCategories = allCategoryKeys.length + (pendingItems.length > 0 ? 1 : 0)

  useEffect(() => {
    localStorage.setItem(storageKey, JSON.stringify([...checked]))
  }, [checked, storageKey])

  // Fetch quantities for each meal once per session
  useEffect(() => {
    mealObjects.forEach(meal => {
      if (!meal.ingredients?.length) return
      if (fetchedRef.current.has(meal.id)) return
      fetchedRef.current.add(meal.id)
      setQuantities(prev => ({ ...prev, [meal.id]: 'loading' }))
      enrichIngredientsWithQuantities(meal.name, meal.ingredients).then(result => {
        setQuantities(prev => ({ ...prev, [meal.id]: result }))
      })
    })
  }, [mealObjects])

  const toggleChecked = (item) => {
    setChecked(prev => {
      const next = new Set(prev)
      if (next.has(item)) next.delete(item)
      else next.add(item)
      return next
    })
  }

  const handleAddManual = () => {
    const val = manualInput.trim()
    if (!val) return
    setManualInput('')
    setPendingItems(prev => [...prev, val])
    categorizeIngredient(val).then(category => {
      setPendingItems(prev => prev.filter(p => p !== val))
      setManualItems(prev => {
        const next = [...prev, { name: val, category }]
        localStorage.setItem(manualKey, JSON.stringify(next))
        return next
      })
    })
  }

  const removeManualItem = (name) => {
    setManualItems(prev => {
      const next = prev.filter(m => m.name !== name)
      localStorage.setItem(manualKey, JSON.stringify(next))
      return next
    })
  }

  const allItemsText = useMemo(() => {
    const allCats = {}
    Object.entries(categories).forEach(([cat, items]) => { allCats[cat] = [...items] })
    manualItems.forEach(item => {
      if (!allCats[item.category]) allCats[item.category] = []
      if (!allCats[item.category].includes(item.name)) allCats[item.category].push(item.name)
    })
    return Object.entries(allCats)
      .map(([cat, items]) => `${cat}:\n${items.map(i => `  - ${i}`).join('\n')}`)
      .join('\n\n')
  }, [categories, manualItems])

  const handleCopyAll = async () => {
    try {
      await navigator.clipboard.writeText(allItemsText)
      setCopied(true)
      setTimeout(() => setCopied(false), 2000)
    } catch { /* ignore */ }
  }

  if (loading) {
    return (
      <div className="page">
        <div className="spinner-wrap"><div className="spinner" /></div>
      </div>
    )
  }

  return (
    <div className="page">
      <div className="page-header">
        <div>
          <h1 className="page-title">Shopping List</h1>
          <p className="page-subtitle">Auto-generated from this week's meals. Check off items as you shop — your progress saves automatically and resets each new week.</p>
          <div className="week-header-meta">
            {totalItems} item{totalItems !== 1 ? 's' : ''} across {totalCategories} categor{totalCategories !== 1 ? 'ies' : 'y'}
            {' · '}{getWeekRange()}
          </div>
        </div>
      </div>

      {/* Action buttons — always below header, 50/50 on mobile */}
      <div className="shop-action-row">
        <button className="btn btn-secondary" onClick={() => setShowSend(true)} disabled={totalItems === 0}>
          📤 Send / Share
        </button>
        <button className="btn btn-secondary" onClick={handleCopyAll} disabled={totalItems === 0}>
          {copied ? '✓ Copied' : 'Copy All'}
        </button>
      </div>

      {/* Manual ingredient input */}
      <div className="manual-add-row">
        <input
          className="form-input manual-add-input"
          value={manualInput}
          onChange={e => setManualInput(e.target.value)}
          onKeyDown={e => e.key === 'Enter' && handleAddManual()}
          placeholder="Add an ingredient…"
        />
        <button className="btn btn-secondary" onClick={handleAddManual} disabled={!manualInput.trim()}>
          Add
        </button>
      </div>

      {totalItems === 0 && pendingItems.length === 0 ? (
        <div className="empty-state">
          <div className="empty-icon">🛒</div>
          <div className="empty-text">Add meals to This Week to generate your shopping list.</div>
        </div>
      ) : (
        <>
          {/* By Recipe — always expanded at top */}
          {mealObjects.length > 0 && (
            <div className="shop-section">
              <div className="shop-section-title">By Recipe</div>
              <div className="by-recipe-grid">
                {mealObjects.map(meal => {
                  const qData = quantities[meal.id]
                  const isLoading = qData === 'loading'
                  const enriched = Array.isArray(qData) ? qData : (meal.ingredients || [])

                  return (
                    <div key={meal.id} className="by-recipe-card card">
                      <div className="by-recipe-card-header">
                        <span className="by-recipe-card-name">{meal.name}</span>
                        {isLoading && <span className="qty-loading">Adding quantities…</span>}
                      </div>
                      <ul className="shop-item-list">
                        {enriched.map(ing => (
                          <li
                            key={ing}
                            className={`shop-item ${checked.has(ing) ? 'checked' : ''}`}
                            onClick={() => toggleChecked(ing)}
                          >
                            <span className="shop-checkbox">{checked.has(ing) ? '✓' : ''}</span>
                            <span className="shop-item-label">{ing}</span>
                          </li>
                        ))}
                      </ul>
                    </div>
                  )
                })}
              </div>
            </div>
          )}

          {/* All Items by Category */}
          <div className="shop-section">
            <div className="shop-section-title">All Items by Category</div>
            <div className="shop-grid">
              {allCategoryKeys.map(cat => {
                const autoItems = categories[cat] || []
                const manualForCat = manualItems.filter(m => m.category === cat)
                if (autoItems.length === 0 && manualForCat.length === 0) return null
                return (
                  <div key={cat} className="shop-card card">
                    <div className="shop-card-title">{cat}</div>
                    <ul className="shop-item-list">
                      {autoItems.map(item => (
                        <li
                          key={item}
                          className={`shop-item ${checked.has(item) ? 'checked' : ''}`}
                          onClick={() => toggleChecked(item)}
                        >
                          <span className="shop-checkbox">{checked.has(item) ? '✓' : ''}</span>
                          <span className="shop-item-label">{item}</span>
                        </li>
                      ))}
                      {manualForCat.map(item => (
                        <li
                          key={item.name}
                          className={`shop-item shop-item-manual ${checked.has(item.name) ? 'checked' : ''}`}
                          onClick={() => toggleChecked(item.name)}
                        >
                          <span className="shop-checkbox">{checked.has(item.name) ? '✓' : ''}</span>
                          <span className="shop-item-label">{item.name}</span>
                          <span className="badge-added">+ added</span>
                          <button
                            className="shop-item-remove"
                            onClick={e => { e.stopPropagation(); removeManualItem(item.name) }}
                          >×</button>
                        </li>
                      ))}
                    </ul>
                  </div>
                )
              })}

              {/* Uncategorized — pending AI response */}
              {pendingItems.length > 0 && (
                <div className="shop-card card">
                  <div className="shop-card-title">Uncategorized</div>
                  <ul className="shop-item-list">
                    {pendingItems.map(item => (
                      <li key={item} className="shop-item">
                        <span className="shop-checkbox" />
                        <span className="shop-item-label">{item}</span>
                        <span className="badge-added qty-loading">categorizing…</span>
                      </li>
                    ))}
                  </ul>
                </div>
              )}
            </div>
          </div>
        </>
      )}

      {showSend && (
        <ShoppingShareModal
          categories={categories}
          manualItems={manualItems}
          mealObjects={mealObjects}
          quantities={quantities}
          onClose={() => setShowSend(false)}
        />
      )}
    </div>
  )
}
